<#
.SYNOPSIS
  Mechanically extract all session files under input/ and replace
  docs/PROMPT-PACK.md section 2 (PROMPT-COLLECTION machine block), idempotently.

.DESCRIPTION
  Strict rules (from trae-session-log prompt-pack rule 4):
    - DO NOT manually rewrite or supplement section 2.
    - Section 2 is wrapped by BEGIN/END PROMPT-COLLECTION markers;
      only the content between markers is replaced.
    - Walk input/**/session-*.md; sort by front matter (date, seq).
    - Extract verbatim content between BEGIN/END VERBATIM PROMPT (no trim, no normalization).
    - Write back as UTF-8 without BOM.
    - Output "extracted Turn count vs actual Turn count" validation.

.NOTES
  This file MUST be saved with UTF-8 BOM so Windows PowerShell 5.1 Desktop
  parses non-ASCII characters correctly.
#>

[CmdletBinding()]
param(
    [string]$ProjectRoot = 'e:\langChain_langGraph',
    [string]$PackPath    = 'e:\langChain_langGraph\docs\PROMPT-PACK.md',
    [string]$InputRoot   = 'e:\langChain_langGraph\input'
)

$ErrorActionPreference = 'Stop'
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)

if (-not (Test-Path $PackPath)) {
    throw "Pack file not found: $PackPath"
}
if (-not (Test-Path $InputRoot)) {
    Write-Output "[WARN] input dir not found: $InputRoot (section 2 will be empty)"
}

$begin = '<!-- BEGIN PROMPT-COLLECTION (generated by scripts/build-prompt-pack.ps1, DO NOT edit) -->'
$end   = '<!-- END PROMPT-COLLECTION -->'

# Read with explicit UTF-8 NO BOM to preserve raw bytes
$rawBytes = [System.IO.File]::ReadAllBytes($PackPath)
$pack = [System.Text.Encoding]::UTF8.GetString($rawBytes)
$startIdx = $pack.IndexOf($begin)
$stopIdx  = $pack.IndexOf($end)
if ($startIdx -lt 0 -or $stopIdx -lt 0 -or $stopIdx -le $startIdx) {
    throw "PROMPT-COLLECTION markers not found in pack. Initialize docs/PROMPT-PACK.md first."
}

# Collect input/**/session-*.md, sorted by front matter (date, seq)
$files = if (Test-Path $InputRoot) {
    Get-ChildItem -LiteralPath $InputRoot -Recurse -Filter 'session-*.md' -File
} else { @() }

$entries = New-Object System.Collections.Generic.List[object]
$actualTurnCount = 0
foreach ($f in $files) {
    # Read raw bytes to avoid PS 5.1 codepage re-encoding
    $rawBytes = [System.IO.File]::ReadAllBytes($f.FullName)
    $raw = [System.Text.Encoding]::UTF8.GetString($rawBytes)
    if ($raw -match '(?s)^---\r?\n(.*?)\r?\n---\r?\n(.*)$') {
        $fmBlock = $matches[1]
        $body    = $matches[2]
    } else { continue }

    $fm = @{}
    foreach ($line in ($fmBlock -split "`r?`n")) {
        if ($line -match '^\s*([A-Za-z_]+)\s*:\s*(.*?)\s*$') {
            $fm[$matches[1]] = $matches[2]
        }
    }
    $date  = $fm['date']
    $seq   = $fm['session_id']  # source annotation only; fileSeq is parsed from filename
    $fname = [System.IO.Path]::GetFileNameWithoutExtension($f.Name)
    $fileSeq = 0
    if ($fname -match 'session-(\d+)') { $fileSeq = [int]$matches[1] }

    # Extract each BEGIN/END VERBATIM PROMPT body
    $rx = [regex]'(?s)<!-- BEGIN VERBATIM PROMPT -->\r?\n(.*?)\r?\n<!-- END VERBATIM PROMPT -->'
    foreach ($m in $rx.Matches($body)) {
        $actualTurnCount++
        $entries.Add([pscustomobject]@{
            Date    = $date
            FileSeq = $fileSeq
            File    = $f.FullName.Substring($ProjectRoot.Length).TrimStart('\','/')
            Verbatim= $m.Groups[1].Value
        })
    }
}

$entries = $entries | Sort-Object Date, FileSeq

# Build the inner block. Note: NO trailing blank line in the per-entry loop,
# so each run produces identical bytes (idempotency fix from D1).
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine($begin)
foreach ($e in $entries) {
    $rel = ($e.File -replace '\\','/')
    [void]$sb.AppendLine("## Turn $($e.Date) source:$rel")
    [void]$sb.AppendLine('<!-- BEGIN VERBATIM PROMPT -->')
    [void]$sb.AppendLine($e.Verbatim)
    [void]$sb.AppendLine('<!-- END VERBATIM PROMPT -->')
    # E1/D1 fix: REMOVED the trailing AppendLine('') here to break the
    # whitespace-accumulation bug (each prior run added one CRLF).
}
# Append end WITHOUT trailing newline (the original section 2 has no CRLF
# after the END marker; adding one would cause the file to grow by 2 bytes
# per run, breaking idempotency).
[void]$sb.Append($end)

$beforeMarker = $pack.Substring(0, $startIdx)
$afterMarker  = $pack.Substring($stopIdx + $end.Length)
$newPack = $beforeMarker + $sb.ToString() + $afterMarker

# Idempotent: do not write if content is unchanged
if ($newPack -ne $pack) {
    [System.IO.File]::WriteAllText($PackPath, $newPack, $utf8NoBom)
}

# Validation
$packTurnCount = ([regex]::Matches($newPack, '<!-- BEGIN VERBATIM PROMPT -->')).Count
Write-Output ("[build-prompt-pack] input actual turns = {0}; pack section 2 turns = {1}; match = {2}" -f $actualTurnCount, $packTurnCount, ($actualTurnCount -eq $packTurnCount))

if ($actualTurnCount -ne $packTurnCount) {
    throw "Turn count mismatch. Check input/ sources and pack section 2."
}

exit 0
